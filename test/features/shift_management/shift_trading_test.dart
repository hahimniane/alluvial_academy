import 'package:flutter_test/flutter_test.dart';
import 'package:alluwalacademyadmin/features/shift_management/enums/shift_enums.dart';
import 'package:alluwalacademyadmin/features/shift_management/models/teaching_shift.dart';
import 'package:alluwalacademyadmin/features/shift_management/services/shift_trading.dart';

void main() {
  // A Wednesday.
  final now = DateTime(2026, 11, 11, 12);

  TeachingShift shift(
    String id,
    DateTime start, {
    String teacherId = 'me',
    String? templateId = 'tpl',
    ShiftStatus status = ShiftStatus.scheduled,
    bool offered = false,
    ShiftCategory category = ShiftCategory.teaching,
  }) =>
      TeachingShift(
        id: id,
        teacherId: teacherId,
        teacherName: 'T',
        studentIds: const ['a'],
        studentNames: const ['A'],
        shiftStart: start,
        shiftEnd: start.add(const Duration(hours: 1)),
        adminTimezone: 'America/New_York',
        teacherTimezone: 'America/New_York',
        subject: IslamicSubject.quranStudies,
        autoGeneratedName: 'T - Quran',
        hourlyRate: 4,
        status: status,
        createdByAdminId: 'admin',
        createdAt: DateTime(2026, 11, 1),
        templateId: templateId,
        isPublished: offered,
        category: category,
      );

  DateTime day(int d, [int hour = 18]) => DateTime(2026, 11, d, hour);

  group('seriesOfferChoices', () {
    final opened = shift('thu', day(12));

    test('lists my upcoming scheduled classes of the same series, in order',
        () {
      final choices = ShiftTrading.seriesOfferChoices(
        opened: opened,
        now: now,
        candidates: [
          shift('mon2', day(16)),
          shift('fri', day(13)),
          opened,
        ],
      );
      expect(choices.map((s) => s.id), ['thu', 'fri', 'mon2']);
    });

    test('leaves out other series, other teachers, started and non-scheduled',
        () {
      final choices = ShiftTrading.seriesOfferChoices(
        opened: opened,
        now: now,
        candidates: [
          shift('other-series', day(13), templateId: 'tpl-2'),
          shift('other-teacher', day(13), teacherId: 'someone'),
          shift('earlier-today', DateTime(2026, 11, 11, 9)),
          shift('cancelled', day(14), status: ShiftStatus.cancelled),
          shift('active', day(15), status: ShiftStatus.active),
          shift('ok', day(16)),
        ],
      );
      expect(choices.map((s) => s.id), ['thu', 'ok']);
    });

    test('stops at 30 days', () {
      final choices = ShiftTrading.seriesOfferChoices(
        opened: opened,
        now: now,
        candidates: [
          shift('day-29', now.add(const Duration(days: 29))),
          shift('day-31', now.add(const Duration(days: 31))),
        ],
      );
      expect(choices.map((s) => s.id), ['thu', 'day-29']);
    });

    test('a one-off class offers only itself', () {
      final oneOff = shift('solo', day(12), templateId: null);
      final choices = ShiftTrading.seriesOfferChoices(
        opened: oneOff,
        now: now,
        candidates: [shift('x', day(13), templateId: null)],
      );
      expect(choices.map((s) => s.id), ['solo']);
    });

    test('keeps a day that is already offered, so it can be shown ticked', () {
      final choices = ShiftTrading.seriesOfferChoices(
        opened: opened,
        now: now,
        candidates: [shift('fri', day(13), offered: true)],
      );
      expect(choices.map((s) => s.id), ['thu', 'fri']);
      expect(choices.last.isPublished, isTrue);
    });
  });

  group('quick picks', () {
    final opened = shift('thu', day(12));
    final choices = [
      opened,
      shift('fri', day(13)),
      shift('sun', day(15)),
      shift('mon2', day(16)),
      shift('tue2', day(17)),
    ];

    test('only this class', () {
      expect(ShiftTrading.pickOnlyThis(opened), {'thu'});
    });

    test('next 3 is the opened class and the two after it', () {
      expect(
        ShiftTrading.pickNext(opened: opened, choices: choices),
        {'thu', 'fri', 'sun'},
      );
    });

    test('next 3 counts from the opened class, not from the first day', () {
      final openedLater = choices[2];
      expect(
        ShiftTrading.pickNext(opened: openedLater, choices: choices),
        {'sun', 'mon2', 'tue2'},
      );
    });

    test('next 3 skips a day that is already offered', () {
      final withOffered = [
        opened,
        shift('fri', day(13), offered: true),
        shift('sun', day(15)),
        shift('mon2', day(16)),
      ];
      expect(
        ShiftTrading.pickNext(opened: opened, choices: withOffered),
        {'thu', 'sun', 'mon2'},
      );
    });

    test('next 3 with fewer days left takes what there is', () {
      expect(
        ShiftTrading.pickNext(opened: opened, choices: [opened]),
        {'thu'},
      );
    });

    test('this week is Monday to Sunday of the opened class', () {
      expect(
        ShiftTrading.pickSameWeek(opened: opened, choices: choices),
        {'thu', 'fri', 'sun'},
      );
    });
  });

  test('idsToOffer sends what is ticked, minus days already offered', () {
    final choices = [
      shift('a', day(12)),
      shift('b', day(13), offered: true),
      shift('c', day(14)),
    ];
    expect(
      ShiftTrading.idsToOffer(ticked: {'a', 'b'}, choices: choices),
      ['a'],
    );
    expect(ShiftTrading.idsToOffer(ticked: {}, choices: choices), isEmpty);
  });

  group('leader', () {
    test('admins and super admins are leaders', () {
      expect(ShiftTrading.isLeader(primaryRole: 'admin'), isTrue);
      expect(ShiftTrading.isLeader(primaryRole: 'Super_Admin'), isTrue);
      expect(
        ShiftTrading.isLeader(primaryRole: 'teacher', activeRole: 'admin'),
        isTrue,
      );
    });

    test('an admin-teacher is a leader', () {
      expect(
        ShiftTrading.isLeader(primaryRole: 'teacher', isAdminTeacher: true),
        isTrue,
      );
    });

    test('a teacher who holds a leadership duty is a leader', () {
      expect(
        ShiftTrading.isLeader(
            primaryRole: 'teacher', holdsLeadershipDuty: true),
        isTrue,
      );
    });

    test('a plain teacher, a parent or nobody is not', () {
      expect(ShiftTrading.isLeader(primaryRole: 'teacher'), isFalse);
      expect(ShiftTrading.isLeader(primaryRole: 'parent'), isFalse);
      expect(ShiftTrading.isLeader(), isFalse);
    });
  });

  group('visibleOffers', () {
    final offered = [
      shift('class', day(12), teacherId: 'a', offered: true),
      shift('duty', day(12),
          teacherId: 'b', offered: true, category: ShiftCategory.leadership),
      shift('meeting', day(13),
          teacherId: 'b', offered: true, category: ShiftCategory.meeting),
      shift('mine', day(12), teacherId: 'me', offered: true),
      shift('over', DateTime(2026, 11, 10, 9), teacherId: 'a', offered: true),
    ];

    test('a plain teacher sees classes only', () {
      final seen = ShiftTrading.visibleOffers(
        offered: offered,
        viewerUid: 'me',
        viewerIsLeader: false,
        now: now,
      );
      expect(seen.map((s) => s.id), ['class']);
    });

    test('a leader also sees leadership duties', () {
      final seen = ShiftTrading.visibleOffers(
        offered: offered,
        viewerUid: 'me',
        viewerIsLeader: true,
        now: now,
      );
      expect(seen.map((s) => s.id), ['class', 'duty', 'meeting']);
    });

    test('anything that is not a taught class is a leadership duty', () {
      expect(ShiftTrading.isLeadershipDuty(offered[0]), isFalse);
      for (final category in ShiftCategory.values) {
        expect(
          ShiftTrading.isLeadershipDuty(
              shift('x', day(12), category: category)),
          category != ShiftCategory.teaching,
        );
      }
    });
  });

  group('setShiftOffers results', () {
    test('reads one result per class', () {
      final results = ShiftTrading.parseResults({
        'success': false,
        'results': [
          {'shiftId': 'a', 'ok': true},
          {
            'shiftId': 'b',
            'ok': false,
            'reason': 'This class has already started'
          },
          {'ok': true},
          'junk',
        ],
      });
      expect(results, hasLength(2));
      expect(results[0].ok, isTrue);
      expect(results[0].failure, isNull);
      expect(results[1].ok, isFalse);
      expect(results[1].failure, ShiftOfferFailure.alreadyStarted);
    });

    test('an answer with no results is no results', () {
      expect(ShiftTrading.parseResults(null), isEmpty);
      expect(ShiftTrading.parseResults({'success': true}), isEmpty);
    });

    test('server reasons map to something the app can say', () {
      expect(
        ShiftTrading.failureFromReason(
            'Only a class that has not started can be offered'),
        ShiftOfferFailure.notScheduled,
      );
      expect(ShiftTrading.failureFromReason('This is not your class'),
          ShiftOfferFailure.notYours);
      expect(ShiftTrading.failureFromReason('Shift not found'),
          ShiftOfferFailure.notFound);
      expect(ShiftTrading.failureFromReason('Could not update this class'),
          ShiftOfferFailure.other);
      expect(ShiftTrading.failureFromReason(null), ShiftOfferFailure.other);
    });
  });
}
