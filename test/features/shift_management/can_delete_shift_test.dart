import 'package:flutter_test/flutter_test.dart';
import 'package:alluwalacademyadmin/features/shift_management/models/teaching_shift.dart';
import 'package:alluwalacademyadmin/features/shift_management/enums/shift_enums.dart';
import 'package:alluwalacademyadmin/features/shift_management/services/shift_service.dart';

void main() {
  final now = DateTime.utc(2026, 11, 5, 12);
  TeachingShift shiftAt(Duration fromNow, ShiftStatus status) => TeachingShift(
        id: 's',
        teacherId: 't',
        teacherName: 'T',
        studentIds: const ['a'],
        studentNames: const ['A'],
        shiftStart: now.add(fromNow),
        shiftEnd: now.add(fromNow + const Duration(hours: 1)),
        adminTimezone: 'America/New_York',
        teacherTimezone: 'America/New_York',
        subject: IslamicSubject.quranStudies,
        autoGeneratedName: 'T - Quran',
        hourlyRate: 4,
        status: status,
        createdByAdminId: 'admin',
        createdAt: DateTime.utc(2026, 11, 1),
      );

  test('an upcoming class can be deleted', () {
    expect(
        ShiftService.canDeleteShift(
            shiftAt(const Duration(days: 1), ShiftStatus.scheduled),
            now: now),
        isTrue);
  });

  test('a class that already happened is never deletable, whatever its status',
      () {
    for (final status in ShiftStatus.values) {
      expect(
          ShiftService.canDeleteShift(
              shiftAt(const Duration(days: -5), status),
              now: now),
          isFalse,
          reason: status.name);
    }
  });

  test('a class running right now cannot be deleted', () {
    expect(
        ShiftService.canDeleteShift(
            shiftAt(const Duration(minutes: -10), ShiftStatus.scheduled),
            now: now),
        isFalse);
  });

  test('a future class already marked completed is kept', () {
    expect(
        ShiftService.canDeleteShift(
            shiftAt(const Duration(days: 1), ShiftStatus.fullyCompleted),
            now: now),
        isFalse);
  });
}
