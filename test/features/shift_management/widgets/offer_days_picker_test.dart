import 'package:alluwalacademyadmin/features/shift_management/enums/shift_enums.dart';
import 'package:alluwalacademyadmin/features/shift_management/models/teaching_shift.dart';
import 'package:alluwalacademyadmin/features/shift_management/widgets/report_schedule_issue_dialog.dart';
import 'package:alluwalacademyadmin/l10n/app_localizations.dart';
import 'package:flutter/material.dart';
import 'package:flutter_localizations/flutter_localizations.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  // The class a week from now, at 6 pm, and the days of its series after it.
  final today = DateTime.now();
  final first = DateTime(today.year, today.month, today.day, 18)
      .add(const Duration(days: 7));

  TeachingShift shift(
    String id,
    int daysAfterFirst, {
    String? templateId = 'tpl',
    bool offered = false,
    ShiftCategory category = ShiftCategory.teaching,
  }) {
    final start = first.add(Duration(days: daysAfterFirst));
    return TeachingShift(
      id: id,
      teacherId: 'me',
      teacherName: 'Teacher One',
      studentIds: const ['s'],
      studentNames: const ['Student One'],
      shiftStart: start,
      shiftEnd: start.add(const Duration(hours: 1)),
      adminTimezone: 'America/New_York',
      teacherTimezone: 'America/New_York',
      subject: IslamicSubject.quranStudies,
      autoGeneratedName: 'Teacher One - Quran',
      hourlyRate: 4,
      status: ShiftStatus.scheduled,
      createdByAdminId: 'admin',
      createdAt: DateTime(2026, 11, 1),
      templateId: templateId,
      isPublished: offered,
      category: category,
    );
  }

  Future<void> pumpDialog(
    WidgetTester tester,
    TeachingShift opened,
    List<TeachingShift> series, {
    Locale locale = const Locale('en'),
  }) async {
    tester.view.physicalSize = const Size(900, 2400);
    tester.view.devicePixelRatio = 1.0;
    addTearDown(tester.view.reset);
    await tester.pumpWidget(
      MaterialApp(
        locale: locale,
        localizationsDelegates: const [
          AppLocalizations.delegate,
          GlobalMaterialLocalizations.delegate,
          GlobalWidgetsLocalizations.delegate,
          GlobalCupertinoLocalizations.delegate,
        ],
        supportedLocales: AppLocalizations.supportedLocales,
        home: Scaffold(
          body: ReportScheduleIssueDialog(
            shift: opened,
            offerChoicesLoader: (_) async => series,
          ),
        ),
      ),
    );
    await tester.pumpAndSettle();
  }

  List<bool?> ticks(WidgetTester tester) => tester
      .widgetList<CheckboxListTile>(find.byType(CheckboxListTile))
      .map((tile) => tile.value)
      .toList();

  testWidgets('a recurring class lists its days; only the opened one is ticked',
      (tester) async {
    final opened = shift('d0', 0);
    final series = [opened, shift('d1', 1), shift('d2', 2), shift('d3', 3)];
    await pumpDialog(tester, opened, series);

    expect(find.byType(CheckboxListTile), findsNothing);
    await tester.tap(find.text('Offer this shift to other teachers'));
    await tester.pumpAndSettle();

    expect(find.text('Which days?'), findsOneWidget);
    expect(ticks(tester), [true, false, false, false]);
  });

  testWidgets('quick picks tick the right days', (tester) async {
    final opened = shift('d0', 0);
    final series = [opened, shift('d1', 1), shift('d2', 2), shift('d3', 3)];
    await pumpDialog(tester, opened, series);
    await tester.tap(find.text('Offer this shift to other teachers'));
    await tester.pumpAndSettle();

    await tester.tap(find.text('Next 3'));
    await tester.pumpAndSettle();
    expect(ticks(tester), [true, true, true, false]);

    await tester.tap(find.text('Only this day'));
    await tester.pumpAndSettle();
    expect(ticks(tester), [true, false, false, false]);

    // A day can also be ticked by hand.
    await tester.tap(find.byType(CheckboxListTile).last);
    await tester.pumpAndSettle();
    expect(ticks(tester), [true, false, false, true]);
  });

  testWidgets('a day that is already offered shows ticked and cannot change',
      (tester) async {
    final opened = shift('d0', 0);
    final series = [opened, shift('d1', 1, offered: true), shift('d2', 2)];
    await pumpDialog(tester, opened, series);
    await tester.tap(find.text('Offer this shift to other teachers'));
    await tester.pumpAndSettle();

    expect(ticks(tester), [true, true, false]);
    expect(find.text('Already offered'), findsOneWidget);
    final offeredTile = tester
        .widgetList<CheckboxListTile>(find.byType(CheckboxListTile))
        .elementAt(1);
    expect(offeredTile.onChanged, isNull);
  });

  testWidgets('a one-off class has no day picker', (tester) async {
    final opened = shift('solo', 0, templateId: null);
    await pumpDialog(tester, opened, [opened]);
    await tester.tap(find.text('Offer this shift to other teachers'));
    await tester.pumpAndSettle();

    expect(find.text('Which days?'), findsNothing);
    expect(find.byType(CheckboxListTile), findsNothing);
  });

  testWidgets('a leadership duty is offered to other leaders', (tester) async {
    final opened = shift('duty', 0, category: ShiftCategory.leadership);
    await pumpDialog(tester, opened, [opened]);

    expect(find.text('Offer this duty to other leaders'), findsOneWidget);
    expect(find.text('Offer this shift to other teachers'), findsNothing);
  });

  testWidgets('the picker reads in French', (tester) async {
    final opened = shift('d0', 0);
    await pumpDialog(tester, opened, [opened, shift('d1', 1)],
        locale: const Locale('fr'));
    await tester.tap(find.text('Proposer ce créneau aux autres enseignants'));
    await tester.pumpAndSettle();

    expect(find.text('Quels jours ?'), findsOneWidget);
    expect(find.text('Ce jour uniquement'), findsOneWidget);
    expect(find.text('Cette semaine'), findsOneWidget);
  });
}
